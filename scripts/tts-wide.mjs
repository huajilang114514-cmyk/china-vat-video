import fs from "node:fs";
import path from "node:path";
import { MsEdgeTTS, OUTPUT_FORMAT } from "msedge-tts";
import { parseFile } from "music-metadata";

const VOICE = process.env.TTS_VOICE || "zh-CN-YunyangNeural";
const lines = JSON.parse(fs.readFileSync("narration-wide.json", "utf8"));
fs.mkdirSync("public/wide-audio", { recursive: true });
const tts = new MsEdgeTTS({ connectionTimeoutMs: 30000, synthesisTimeoutMs: 90000 });
await tts.setMetadata(VOICE, OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3);
const manifest = {};
for (const line of lines) {
  const target = path.resolve("public/wide-audio", line.id + ".mp3");
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const { audioFilePath } = await tts.toFile(path.resolve("public/wide-audio"), line.text, { rate: "+5%" });
      fs.copyFileSync(audioFilePath, target);
      fs.unlinkSync(audioFilePath);
      const meta = await parseFile(target);
      manifest[line.id] = { audio: "wide-audio/" + line.id + ".mp3", seconds: meta.format.duration };
      console.log("OK", line.id, meta.format.duration.toFixed(2) + "s");
      break;
    } catch (e) {
      console.log("RETRY", line.id, attempt, String(e && e.message ? e.message : e));
      await new Promise((r) => setTimeout(r, 1500));
    }
  }
}
tts.close();
const ts = "// generated by scripts/tts-wide.mjs\nexport const WIDE_NARRATION: Record<string, { audio: string; seconds: number }> = " + JSON.stringify(manifest, null, 2) + ";\n";
fs.writeFileSync("src/wide-narration.ts", ts);
console.log("TOTAL", Object.values(manifest).reduce((a, b) => a + b.seconds, 0).toFixed(1) + "s");
